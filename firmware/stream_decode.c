static stream_decode_stats_t stats;

// Cortex-M0+ supports aligned 32-bit atomic loads/stores, but not
// __atomic_fetch_add_4 without an external runtime. Single writer: Core 0.
static void increment(uint32_t *p) {
    uint32_t v = __atomic_load_n(p, __ATOMIC_RELAXED);
    __atomic_store_n(p, v + 1u, __ATOMIC_RELAXED);
}

void stream_decode_init(void) {
    // Must only be called before the producer and consumer start.
    uint32_t *p = (uint32_t *)&stats;
    for (unsigned i = 0; i < sizeof(stats)/sizeof(uint32_t); ++i)
        __atomic_store_n(&p[i], 0, __ATOMIC_RELAXED);
}

void stream_decode_get_stats(stream_decode_stats_t *out) {
    const uint32_t *p = (const uint32_t *)&stats;
    uint32_t *q = (uint32_t *)out;
    // processed is updated last with RELEASE by Core 0.
    uint32_t done = __atomic_load_n(&stats.processed, __ATOMIC_ACQUIRE);
    for (unsigned i = 1; i < sizeof(stats)/sizeof(uint32_t); ++i)
        q[i] = __atomic_load_n(&p[i], __ATOMIC_RELAXED);
    q[0] = done;
}

static uint16_t crc16_usb(const uint8_t *data, int size) {
    uint16_t crc = 0xffff;
    for (int i = 0; i < size; i++)
        crc = crc16_usb_tab[(crc ^ data[i]) & 0xff] ^ (crc >> 8);
    return crc;
}

static uint8_t crc5_usb(const uint8_t *data, int size) {
    uint8_t crc = 0xff;
    for (int i = 0; i < size; i++)
        crc = crc5_usb_tab[(crc ^ data[i]) & 0xff] ^ (crc >> 8);
    return crc;
}

void stream_decode_packet(const stream_packet_t *packet) {
    uint32_t error = 0;
    uint8_t decoded[256];
    int out_size = 0;
    int out_bit = 0;
    int out_byte = 0;
    int stuff_count = 0;
    uint32_t v = 0x80000000u;

    // Original process_buffer() called process_packet(size - 1).
    uint32_t remaining = (packet->bit_count > 0) ? packet->bit_count - 1u : 0u;
    uint32_t word = 0;

    // The original process_buffer() treats 0 as bus reset, and 1 as
    // an FS event to discard. Neither is a malformed USB packet.
    if (packet->bit_count <= 1u)
        goto done;
    if (remaining > packet->word_count * 31u) {
        error |= CAPTURE_ERROR_SIZE;
        goto done;
    }

    while (remaining) {
        if (word >= packet->word_count) {
            error |= CAPTURE_ERROR_SIZE;
            break;
        }
        uint32_t w = packet->words[word++];
        uint32_t bits = remaining < 31u ? remaining : 31u;
        if (bits < 31u) w <<= (30u - bits);
        v ^= w ^ (w << 1);

        for (uint32_t i = 0; i < bits; i++) {
            int bit = (v & 0x80000000u) ? 0 : 1;
            v <<= 1;
            if (stuff_count == 6) {
                if (bit) error |= CAPTURE_ERROR_STUFF;
                stuff_count = 0;
                continue;
            }
            if (bit)
                stuff_count++;
            else
                stuff_count = 0;
            out_byte |= bit << out_bit;
            out_bit++;
            if (out_bit == 8) {
                if (out_size >= (int)sizeof(decoded)) {
                    error |= CAPTURE_ERROR_SIZE;
                    goto done;
                }
                decoded[out_size++] = (uint8_t)out_byte;
                out_byte = 0;
                out_bit = 0;
            }
        }
        remaining -= bits;
    }

    if (out_bit) error |= CAPTURE_ERROR_NBIT;
    if (out_size < 2) { error |= CAPTURE_ERROR_SIZE; goto done; }

    // Targets Full-Speed. Low-Speed support can be configured later.
    if (decoded[0] != 0x80) error |= CAPTURE_ERROR_SYNC;

    int pid = decoded[1] & 0x0f;
    int npid = (~decoded[1] >> 4) & 0x0f;
    if (pid != npid || pid == Pid_Reserved) error |= CAPTURE_ERROR_PID;

    if (pid == Pid_Sof || pid == Pid_In || pid == Pid_Out ||
        pid == Pid_Setup || pid == Pid_Ping || pid == Pid_Split) {
        if ((pid == Pid_Split && out_size != 5) ||
            (pid != Pid_Split && out_size != 4))
            error |= CAPTURE_ERROR_SIZE;
        else if (crc5_usb(&decoded[2], out_size - 2) != 0x09)
            error |= CAPTURE_ERROR_CRC;
    }
    else if (pid == Pid_Data0 || pid == Pid_Data1 ||
             pid == Pid_Data2 || pid == Pid_MData) {
        if (out_size < 4) error |= CAPTURE_ERROR_SIZE;
        else if (crc16_usb(&decoded[2], out_size - 2) != 0xb001)
            error |= CAPTURE_ERROR_CRC;
    }

    if (!error) {
        if (pid == Pid_In) increment(&stats.in);
        else if (pid == Pid_Data0 || pid == Pid_Data1) increment(&stats.data);
        else if (pid == Pid_Sof) increment(&stats.sof);
    }

done:
    if (error) increment(&stats.errors);
    else       increment(&stats.valid);
    
    if (error & CAPTURE_ERROR_CRC)   increment(&stats.crc);
    if (error & CAPTURE_ERROR_PID)   increment(&stats.pid);
    if (error & CAPTURE_ERROR_STUFF) increment(&stats.stuff);
    if (error & CAPTURE_ERROR_SYNC)  increment(&stats.sync);
    if (error & CAPTURE_ERROR_NBIT)  increment(&stats.nbit);
    if (error & CAPTURE_ERROR_SIZE)  increment(&stats.size);

    // Publication fence: the producer observes all prior statistics once
    // processed reaches its expected value.
    uint32_t count = __atomic_load_n(&stats.processed, __ATOMIC_RELAXED);
    __atomic_store_n(&stats.processed, count + 1u, __ATOMIC_RELEASE);
}
